"""The published detection evaluation must match what the code produces.

`docs/detection-evaluation.md` and `eval/corpus/` are generated by
`scripts/evaluate_detection.py`. Like the frontend types, a committed artefact
that can drift from its source will drift, and a results table that no longer
reproduces is worse than none. Regenerate with:

    python scripts/evaluate_detection.py --write
"""

from __future__ import annotations

import pathlib

from eval.corpus import build
from scripts.evaluate_detection import (
    CORPUS_DIR,
    DEFAULT,
    DOC,
    END,
    START,
    render,
    run_all,
)

BACKEND = pathlib.Path(__file__).resolve().parents[1]


def test_committed_corpus_is_current():
    syslog, cloudtrail, _ = build()
    assert (CORPUS_DIR / "auth.log").read_text(encoding="utf-8") == syslog
    assert (CORPUS_DIR / "cloudtrail.json").read_text(encoding="utf-8") == cloudtrail


def test_published_tables_are_current():
    runs, scenarios, syslog, cloudtrail = run_all()
    generated = render(runs, scenarios, syslog, cloudtrail)
    committed = DOC.read_text(encoding="utf-8").split(START, 1)[1].split(END, 1)[0]
    assert committed.strip() == generated.strip(), (
        "docs/detection-evaluation.md is stale; run "
        "`python scripts/evaluate_detection.py --write`"
    )


def test_labelled_misses_and_false_positives_behave_as_labelled():
    """The doc says these are known; keep them honest if behaviour changes."""
    runs, scenarios, _, _ = run_all()
    run = runs[DEFAULT]
    by_name = {s.name: s for s in scenarios}
    for name, result in run.results.items():
        scenario = by_name[name]
        if scenario.known_miss:
            assert result.misses, f"{name} is labelled a known miss but was detected"
    flagged = run.benign_flagged()
    for scenario in scenarios:
        if scenario.known_false_positive:
            assert scenario.name in flagged, (
                f"{scenario.name} is labelled a known false positive but stayed silent"
            )


def test_readme_headline_matches_the_evaluation():
    runs, _, _, _ = run_all()
    run = runs[DEFAULT]
    readme = (BACKEND.parent / "README.md").read_text(encoding="utf-8")
    flagged = len(run.benign_flagged())
    assert f"**{run.hits} of {run.expected_total}**" in readme
    assert f"**{flagged} of {run.benign_total}**" in readme
